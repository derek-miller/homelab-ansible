STUB = """#!/usr/bin/env python3
import json, os, sys
name = os.path.basename(sys.argv[0])
key = " ".join([name] + sys.argv[1:])
with open(os.environ["STUB_LOG"], "a") as f:
    f.write(json.dumps([name] + sys.argv[1:]) + "\\n")
with open(os.environ["STUB_CANNED"]) as f:
    canned = json.load(f)
sys.stdout.write(canned["out"].get(key, ""))
sys.exit(canned["rc"].get(key, 0))
"""

COMMANDS = ("iptables", "iptables-save", "ip6tables", "ip6tables-save", "ip", "ipset", "nft",
            "systemctl", "umount")


def harness(out=None, rc=None):
    """Return (module, calls) with every command the script runs stubbed."""
    tmp = tempfile.mkdtemp()
    stub = os.path.join(tmp, "stub")
    with open(stub, "w") as f:
        f.write(STUB)
    os.chmod(stub, 0o755)
    for name in COMMANDS:
        os.symlink(stub, os.path.join(tmp, name))
    canned = os.path.join(tmp, "canned.json")
    with open(canned, "w") as f:
        json.dump({"out": out or {}, "rc": rc or {}}, f)
    log = os.path.join(tmp, "log")
    open(log, "w").close()
    os.environ["PATH"] = tmp + os.pathsep + "/usr/bin:/bin"
    os.environ["STUB_LOG"] = log
    os.environ["STUB_CANNED"] = canned
    spec = importlib.util.spec_from_loader("k3s_teardown", importlib.machinery.SourceFileLoader("k3s_teardown", SCRIPT))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)

    def calls():
        with open(log) as f:
            return [json.loads(line) for line in f]

    return mod, calls


def test_iptables_removes_only_k3s_state():
    mod, calls = harness(out={"iptables-save": IPV4})
    mod.remove_iptables("iptables")
    log = [c for c in calls() if c[0] == "iptables"]
    deletes = [(c[3], c[5], c[6:]) for c in log if c[4] == "-D"]
    flushes = [(c[3], c[5]) for c in log if c[4] == "-F"]
    removes = [(c[3], c[5]) for c in log if c[4] == "-X"]

    check("every command waits for the xtables lock", all(c[1] == "-w" for c in log), True)
    check("only -D, -F and -X are issued", sorted({c[4] for c in log}), ["-D", "-F", "-X"])
    check(
        "deletes only rules in built-in or foreign chains",
        all(not re.match(r"KUBE-|CNI-|FLANNEL-", chain) for _, chain, _ in deletes),
        True,
    )
    check(
        "deletes every jump into k3s state",
        sorted((t, c, a[-1]) for t, c, a in deletes),
        sorted([
            ("filter", "INPUT", "KUBE-ROUTER-INPUT"),
            ("filter", "INPUT", "KUBE-PROXY-FIREWALL"),
            ("filter", "INPUT", "KUBE-NODEPORTS"),
            ("filter", "INPUT", "KUBE-FIREWALL"),
            ("filter", "FORWARD", "KUBE-ROUTER-FORWARD"),
            ("filter", "FORWARD", "KUBE-FORWARD"),
            ("filter", "FORWARD", "KUBE-SERVICES"),
            ("filter", "FORWARD", "FLANNEL-FWD"),
            ("filter", "OUTPUT", "KUBE-ROUTER-OUTPUT"),
            ("filter", "OUTPUT", "KUBE-FIREWALL"),
            ("nat", "PREROUTING", "KUBE-SERVICES"),
            ("nat", "PREROUTING", "CNI-HOSTPORT-DNAT"),
            ("nat", "OUTPUT", "KUBE-SERVICES"),
            ("nat", "POSTROUTING", "KUBE-POSTROUTING"),
            ("nat", "POSTROUTING", "CNI-HOSTPORT-MASQ"),
            ("nat", "POSTROUTING", "FLANNEL-POSTRTG"),
        ]),
    )
    check(
        "a quoted comment survives as one argument",
        ["-m", "comment", "--comment", "flanneld forward", "-j", "FLANNEL-FWD"] in [a for _, _, a in deletes],
        True,
    )
    touched = " ".join(" ".join(c) for c in log)
    check("no Docker chain or rule is touched", "DOCKER" in touched or "docker" in touched, False)
    check("no Tailscale chain or rule is touched", "ts-" in touched or "tailscale" in touched, False)
    check(
        "flushes exactly the k3s chains",
        sorted(flushes),
        sorted([
            ("mangle", "KUBE-IPTABLES-HINT"), ("mangle", "KUBE-KUBELET-CANARY"),
            ("filter", "FLANNEL-FWD"), ("filter", "KUBE-EXTERNAL-SERVICES"), ("filter", "KUBE-FIREWALL"),
            ("filter", "KUBE-FORWARD"), ("filter", "KUBE-NODEPORTS"), ("filter", "KUBE-PROXY-FIREWALL"),
            ("filter", "KUBE-ROUTER-FORWARD"), ("filter", "KUBE-ROUTER-INPUT"),
            ("filter", "KUBE-ROUTER-OUTPUT"), ("filter", "KUBE-SERVICES"),
            ("nat", "CNI-DN-1a2b3c4d5e"), ("nat", "CNI-HOSTPORT-DNAT"), ("nat", "CNI-HOSTPORT-MASQ"),
            ("nat", "FLANNEL-POSTRTG"), ("nat", "KUBE-POSTROUTING"), ("nat", "KUBE-SERVICES"),
        ]),
    )
    check("deletes every chain it flushes", sorted(removes), sorted(flushes))
    flags = [c[4] for c in log]
    check("unhooks before flushing", max(i for i, f in enumerate(flags) if f == "-D")
          < min(i for i, f in enumerate(flags) if f == "-F"), True)
    for table in ("mangle", "filter", "nat"):
        idx = [(i, c[4]) for i, c in enumerate(log) if c[3] == table and c[4] in ("-F", "-X")]
        last_flush = max(i for i, f in idx if f == "-F")
        first_delete = min(i for i, f in idx if f == "-X")
        check("%s: flushes every chain before deleting any" % table, last_flush < first_delete, True)
    check("reports a change", mod.changed, True)
    check("reports no errors", mod.errors, [])


def test_ip6tables_is_cleaned_the_same_way():
    mod, calls = harness(out={"ip6tables-save": IPV6})
    mod.remove_iptables("ip6tables")
    log = [c for c in calls() if c[0] == "ip6tables"]
    check(
        "ip6tables: unhooks, flushes and deletes KUBE-FIREWALL only",
        [c[4:] for c in log],
        [["-D", "INPUT", "-j", "KUBE-FIREWALL"], ["-F", "KUBE-FIREWALL"], ["-X", "KUBE-FIREWALL"]],
    )


def test_failed_commands_are_reported():
    mod, _ = harness(
        out={"ip6tables-save": IPV6},
        rc={"ip6tables -w -t filter -X KUBE-FIREWALL": 1},
    )
    mod.remove_iptables("ip6tables")
    check("a failed chain delete is an error", len(mod.errors), 1)


def test_links_and_netns():
    mod, calls = harness(
        out={
            "ip -o link show master cni0": (
                "7: vethaaaa1111@if2: <BROADCAST,MULTICAST,UP,LOWER_UP> mtu 1450 qdisc noqueue master cni0\n"
                "9: vethbbbb2222@if2: <BROADCAST,MULTICAST,UP,LOWER_UP> mtu 1450 qdisc noqueue master cni0\n"
            ),
            "ip netns list": "cni-1111-2222 (id: 3)\ncni-3333-4444 (id: 4)\nother-ns\n",
        },
        rc={
            "ip link show flannel-v6.1": 1,
            "ip link show flannel-wg": 1,
            "ip link show flannel-wg-v6": 1,
            "ip link show kube-ipvs0": 1,
        },
    )
    mod.remove_netns()
    mod.remove_links()
    deleted = [c[1:] for c in calls() if c[0] == "ip" and "delete" in c]
    check(
        "deletes the cni netns and links, nothing else",
        deleted,
        [
            ["netns", "delete", "cni-1111-2222"],
            ["netns", "delete", "cni-3333-4444"],
            ["link", "delete", "vethaaaa1111"],
            ["link", "delete", "vethbbbb2222"],
            ["link", "delete", "cni0"],
            ["link", "delete", "flannel.1"],
        ],
    )


def test_a_veth_gone_before_its_delete_is_not_an_error():
    mod, calls = harness(
        out={
            "ip -o link show master cni0": (
                "7: vethaaaa1111@if2: <BROADCAST,MULTICAST,UP,LOWER_UP> mtu 1450 qdisc noqueue master cni0\n"
                "9: vethbbbb2222@if2: <BROADCAST,MULTICAST,UP,LOWER_UP> mtu 1450 qdisc noqueue master cni0\n"
            ),
        },
        rc={
            "ip link delete vethaaaa1111": 1,
            "ip link show vethaaaa1111": 1,
            "ip link delete vethbbbb2222": 2,
            "ip link show cni0": 1,
            "ip link show flannel.1": 1,
            "ip link show flannel-v6.1": 1,
            "ip link show flannel-wg": 1,
            "ip link show flannel-wg-v6": 1,
            "ip link show kube-ipvs0": 1,
        },
    )
    mod.remove_links()
    check("only the veth still there is an error", [e.split(":")[0] for e in mod.errors], ["ip link delete vethbbbb2222"])


def test_ipsets_and_nft_tables():
    mod, calls = harness(
        out={
            "ipset list -n": "KUBE-DST-ABC\nkube-router-local-ips\nts-something\nmyset\n",
            "nft list tables": "table ip filter\ntable ip kube-proxy\ntable inet flannel\n"
                               "table ip docker-bridges\ntable ip nat\n",
        }
    )
    mod.remove_ipsets()
    mod.remove_nft_tables()
    log = calls()
    check(
        "destroys only k3s ipsets",
        [c[2] for c in log if c[:2] == ["ipset", "destroy"]],
        ["KUBE-DST-ABC", "kube-router-local-ips"],
    )
    check(
        "deletes only k3s nft tables",
        [c[3:] for c in log if c[:3] == ["nft", "delete", "table"]],
        [["ip", "kube-proxy"], ["inet", "flannel"]],
    )


def test_never_runs_the_stock_scripts_or_touches_tailscale():
    with open(SCRIPT) as f:
        tree = ast.parse(f.read())
    docstring = ast.get_docstring(tree, clean=False)
    strings = [n.value for n in ast.walk(tree)
               if isinstance(n, ast.Constant) and isinstance(n.value, str) and n.value != docstring]
    check("teardown never names tailscale", any("tailscale" in s.lower() for s in strings), False)
    check("teardown never restores a whole table", any("-restore" in s for s in strings), False)
    with open(ABSENT) as f:
        absent = "".join(line for line in f if not line.lstrip().startswith("#"))
    check("absent.yml never runs k3s-killall.sh", "killall" in absent, False)
    check("absent.yml never runs k3s-uninstall.sh", "uninstall" in absent, False)


def test_absent_removes_what_present_installs():
    with open(PRESENT) as f:
        present = f.read()
    with open(ABSENT) as f:
        absent = f.read()
    for path in ("/usr/local/bin/k3s", "/etc/rancher/k3s", "/etc/sysctl.d/90-k3s.conf"):
        check("present writes %s" % path, path in present, True)
        check("absent removes %s" % path, path in absent, True)
    for link in ("kubectl", "crictl"):
        check("present links %s" % link, re.search(r"^\s+- %s$" % link, present, re.M) is not None, True)
        check("absent unlinks %s" % link, re.search(r"^\s+- %s$" % link, absent, re.M) is not None, True)
    check("absent removes both unit names", "- k3s\n" in absent and "- k3s-agent\n" in absent, True)
    check("absent removes the data dir", "{{ k3s_data_dir }}" in absent, True)


for fn in (
    test_iptables_removes_only_k3s_state,
    test_ip6tables_is_cleaned_the_same_way,
    test_failed_commands_are_reported,
    test_links_and_netns,
    test_a_veth_gone_before_its_delete_is_not_an_error,
    test_ipsets_and_nft_tables,
    test_never_runs_the_stock_scripts_or_touches_tailscale,
    test_absent_removes_what_present_installs,
):
    fn()

failed = results.count(False)
print("\n%d passed, %d failed" % (results.count(True), failed))
sys.exit(1 if failed else 0)
